// Writes src/assets/dark.css: dark mode by flipping the colour scales the light UI uses
// (50 <-> 950, 100 <-> 900, ...; white becomes a dark surface), so "light background,
// dark text" classes turn into "dark background, light text" without a dark: variant on
// every class. Parts that are dark already (the activity log, the HUD preview) get the
// original colours back with the .keep-colors class.
// Run after changing the palette: node scripts/gen-dark-palette.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const tailwind = fs.readFileSync(path.join(root, 'node_modules/tailwindcss/theme.css'), 'utf8');
const ownTheme = fs.readFileSync(path.join(root, 'src/assets/main.css'), 'utf8');

const value = (source, name) => {
  const m = new RegExp(`--color-${name}:\\s*([^;]+);`).exec(source);
  return m ? m[1].trim() : null;
};

// Families the light UI is made of; the dark parts' own colours are restored, not flipped.
const FLIPPED = ['slate', 'primary', 'red', 'amber', 'emerald', 'green'];
const RESTORED = [...FLIPPED, 'rose', 'sky', 'violet', 'teal', 'fuchsia', 'cyan'];
const SHADES = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900', '950'];

const palette = (family) => Object.fromEntries(SHADES.map(shade => [shade, value(family === 'primary' ? ownTheme : tailwind, `${family}-${shade}`)]));

const flipped = [];
FLIPPED.forEach(family => {
  const p = palette(family);
  SHADES.forEach((shade, i) => {
    const other = p[SHADES[SHADES.length - 1 - i]] || p[shade];
    if (other) flipped.push(`    --color-${family}-${shade}: ${other};`);
  });
});

const restored = [];
RESTORED.forEach(family => {
  const p = palette(family);
  SHADES.forEach(shade => {
    if (p[shade]) restored.push(`    --color-${family}-${shade}: ${p[shade]};`);
  });
});

const slate = palette('slate');
const css = `/* Generated by scripts/gen-dark-palette.mjs; don't edit by hand. */
/* Dark mode: html.theme-dark (set by src/lib/theme.js). */

html.theme-dark {
    color-scheme: dark;
${flipped.join('\n')}
    /* Cards and inputs: the darkest surface but one; page backgrounds use slate-50/100. */
    --color-white: ${slate['900']};
    /* Nuxt UI's tokens that aren't made of the palette. */
    --ui-bg: var(--color-white);
    --ui-bg-inverted: ${slate['50']};
    --ui-text-highlighted: ${slate['50']};
    --ui-border-inverted: ${slate['50']};
}

/* Nuxt UI sets the body's scheme itself (dark only under its own .dark class). */
html.theme-dark body {
    color-scheme: dark;
}

html.theme-dark .keep-colors {
${restored.join('\n')}
    --color-white: #fff;
}
`;
fs.writeFileSync(path.join(root, 'src/assets/dark.css'), css);
console.log(`Wrote src/assets/dark.css (${flipped.length} flipped, ${restored.length} restored).`);
